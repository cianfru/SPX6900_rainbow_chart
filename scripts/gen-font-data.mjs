// Regenerate scripts/bot/font-data.js from the bundled DejaVu .ttf files. The
// embedded base64 is what guarantees the card font survives on fontless serverless
// runtimes (Vercel /api/og): a JS import is traced into the function bundle, where
// a filesystem .ttf can be silently dropped by an includeFiles glob.
//   Run:  node scripts/gen-font-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const b64 = name => readFileSync(join(here, "bot", name)).toString("base64");
const out =
`// AUTO-GENERATED by scripts/gen-font-data.mjs — do not edit by hand.
// DejaVu Sans (regular + bold) embedded as base64 so the bundled font is traced
// into the Vercel function by a normal JS import — never lost to an includeFiles
// glob the way a filesystem-read .ttf can be.
export const REGULAR_B64 = "${b64("DejaVuSans.ttf")}";
export const BOLD_B64 = "${b64("DejaVuSans-Bold.ttf")}";
`;
writeFileSync(join(here, "bot", "font-data.js"), out);
console.log(`font-data.js written (${(out.length / 1024 / 1024).toFixed(2)} MB)`);
