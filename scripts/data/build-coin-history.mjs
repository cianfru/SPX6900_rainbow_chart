// Fetch ETH & SOL daily USD closes from Coinbase since SPX6900's launch and write
// src/eth-history.js / src/sol-history.js — the bundled history the "SPX vs majors
// since launch" flex card needs (majors come from the API as only ~1y otherwise).
// Mirrors how btc-history.js is generated.
//
// Run where outbound network is allowed (GitHub Actions or locally) — NOT the
// agent sandbox, whose egress proxy blocks these hosts:
//   node scripts/data/build-coin-history.mjs
import { writeFileSync } from "node:fs";

const START = "2023-08-17";          // SPX6900's first print
const DAY = 86400000;
const WINDOW = 290 * DAY;            // Coinbase caps a candles request at 300 buckets
const COINS = [["ETH-USD", "ETH", "Ethereum"], ["SOL-USD", "SOL", "Solana"]];

const sleep = ms => new Promise(r => setTimeout(r, ms));

// Daily closes (date -> close) for a Coinbase product, paged back to START.
async function dailyCloses(product) {
  const out = new Map();
  const now = Date.now();
  for (let from = new Date(START + "T00:00:00Z").getTime(); from < now; from += WINDOW + DAY) {
    const to = Math.min(from + WINDOW, now);
    const url = `https://api.exchange.coinbase.com/products/${product}/candles`
      + `?granularity=86400&start=${new Date(from).toISOString()}&end=${new Date(to).toISOString()}`;
    let rows;
    for (let attempt = 0; ; attempt++) {
      const r = await fetch(url, { headers: { "User-Agent": "spx6900-history", Accept: "application/json" } });
      if (r.ok) { rows = await r.json(); break; }
      if (attempt >= 3) throw new Error(`${product} ${r.status} @ ${new Date(from).toISOString().slice(0, 10)}`);
      await sleep(1000 * (attempt + 1));
    }
    for (const [t, , , , close] of rows) out.set(new Date(t * 1000).toISOString().slice(0, 10), close); // [time,low,high,open,close,vol]
    await sleep(350); // be gentle on the public endpoint
  }
  return [...out.entries()].filter(([d]) => d >= START).sort((a, b) => a[0].localeCompare(b[0]));
}

// Keep every ~3rd day plus always the latest point, to match btc-history's density.
function sample(rows, everyN = 3) {
  const out = [];
  for (let i = 0; i < rows.length; i += everyN) out.push(rows[i]);
  if (rows.length && out.at(-1)[0] !== rows.at(-1)[0]) out.push(rows.at(-1));
  return out;
}

function emit(sym, name, rows) {
  if (rows.length < 30) throw new Error(`${sym}: only ${rows.length} days — refusing to write a stub`);
  const pts = sample(rows).map(([d, p]) => `["${d}",${+p.toFixed(p < 10 ? 4 : 2)}]`).join(",");
  const body =
`// ${name} (USD) daily closes from Coinbase since SPX6900's launch, sampled every
// ~3 days. [isoDate, price]. Used by the "SPX vs majors since launch" card.
// Generated by scripts/data/build-coin-history.mjs — do not hand-edit.
export const ${sym}_HISTORY = [${pts}];
`;
  writeFileSync(new URL(`../../src/${sym.toLowerCase()}-history.js`, import.meta.url), body);
  console.log(`${sym}: ${rows.length} daily closes -> src/${sym.toLowerCase()}-history.js (${sample(rows).length} pts, ${rows[0][0]}..${rows.at(-1)[0]})`);
}

for (const [product, sym, name] of COINS) emit(sym, name, await dailyCloses(product));
